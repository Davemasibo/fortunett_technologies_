USE fortunett_technologies;

-- -------------------------------------------------------
-- 1. Platform Subscription Plans
--    Defines the tiers ISPs can subscribe to on FortuNett
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS platform_subscription_plans (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(50) UNIQUE NOT NULL,
    pppoe_fee_per_user DECIMAL(10,2) NOT NULL DEFAULT 25.00 COMMENT 'KSH per PPPoE user per month',
    hotspot_commission_rate DECIMAL(5,4) NOT NULL DEFAULT 0.0300 COMMENT 'Fraction of hotspot revenue e.g. 0.03 = 3%',
    base_monthly_fee DECIMAL(10,2) NOT NULL DEFAULT 0.00 COMMENT 'Fixed monthly platform fee',
    max_clients INT DEFAULT NULL COMMENT 'NULL = unlimited',
    max_routers INT DEFAULT NULL COMMENT 'NULL = unlimited',
    trial_days INT NOT NULL DEFAULT 30,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

