-- 3. Extend tenants table
-- -------------------------------------------------------
ALTER TABLE tenants
    ADD COLUMN IF NOT EXISTS subscription_plan_id INT DEFAULT NULL COMMENT 'FK to platform_subscription_plans',
    ADD COLUMN IF NOT EXISTS notes TEXT DEFAULT NULL COMMENT 'Super-admin internal notes',
    ADD COLUMN IF NOT EXISTS suspended_at TIMESTAMP NULL COMMENT 'When the tenant was last suspended',
    ADD COLUMN IF NOT EXISTS suspended_reason VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(30) NULL;

-- Default all existing tenants to Starter plan
UPDATE tenants SET subscription_plan_id = 1 WHERE subscription_plan_id IS NULL;

ALTER TABLE tenants
    ADD CONSTRAINT fk_tenant_plan FOREIGN KEY (subscription_plan_id)
        REFERENCES platform_subscription_plans(id) ON DELETE SET NULL;

